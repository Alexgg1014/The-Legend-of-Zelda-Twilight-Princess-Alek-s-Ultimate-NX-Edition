// aleks2: code mods on Switch.
//
// Horizon has no dlopen -- there is no dynamic loader for homebrew to call, so
// upstream's NativeModule cannot work, and a loader that simply refuses native
// mods ("not supported on this platform") does more damage than it looks: Luau
// support is itself a native mod (dev.twilitrealm.luau), so refusing native mods
// took every script mod down with it and left the console with asset mods only.
//
// A mod does not actually need to be a shared library. The loader only wants
// five symbols out of one (see loader/natives.cpp), so a mod compiled into the
// NRO can offer exactly those through a table built at link time. The bundle on
// the SD card still carries mod.json and res/; only the code comes from inside.
//
// The table is generated by platforms/switch/cmake/StaticMods.cmake.
#pragma once

#include <filesystem>
#include <string_view>

namespace dusk::mods::loader {

// The five exports the loader looks up, for one mod linked into the executable.
struct BuiltinMod {
    const char* id;
    const void* meta;        // const ModMeta*
    void* context;           // ModContext**
    void* initialize;        // ModInitializeFn
    void* update;            // ModUpdateFn
    void* shutdown;          // ModShutdownFn
};

// aleks2 (H36): one name a built-in mod asks the host to resolve by name -- a hook
// declared with DEFINE_HOOK_SYMBOL, or the vtable of a hooked virtual member. On
// desktop those come from the symbol manifest symgen embeds after linking; this
// build has none, so platforms/switch/tools/static_mod_link.py lists the names the
// sealed mods' metadata asks for and the linker fills in their addresses through
// weak references. A null address is a name this link did not have.
struct BuiltinSymbol {
    const char* name;     // exactly as the mod's metadata spells it
    const void* address;  // null when the link had no such symbol
    bool code;            // a function (a hook target) rather than data (a vtable)
};

namespace detail {
// The table itself, generated by StaticMods.cmake and terminated by a null id.
// Declared here so that both it and the lookup see external linkage: a const
// array defined at namespace scope without a prior extern declaration would be
// internal to its own translation unit.
extern const BuiltinMod kBuiltinMods[];
// Generated by static_mod_link.py at build time, terminated by a null name.
extern const BuiltinSymbol kBuiltinSymbols[];

// The lookup over any table of that shape; inline so that the host test
// (platforms/switch/tools/test-static-mods.sh) runs this very code on a generated table.
inline const BuiltinSymbol* find_builtin_symbol(const BuiltinSymbol* table, std::string_view name) {
    if (table == nullptr || name.empty()) {
        return nullptr;
    }
    for (const BuiltinSymbol* entry = table; entry->name != nullptr; entry++) {
        if (name == entry->name) {
            return entry;
        }
    }
    return nullptr;
}
}  // namespace detail

// Null when this build carries no code for that mod id.
const BuiltinMod* builtin_mod(std::string_view id);

// Null when no built-in mod asked for that name, so the table has no entry for it.
// An entry whose address is null means the name was asked for and the link did not
// have it: the caller reports that as not found.
const BuiltinSymbol* builtin_symbol(std::string_view name);

// What gets logged and stored as the mod's native path. Nothing opens it: it
// names where the code came from, which is the executable itself.
std::filesystem::path builtin_mod_path(std::string_view id);

}  // namespace dusk::mods::loader
