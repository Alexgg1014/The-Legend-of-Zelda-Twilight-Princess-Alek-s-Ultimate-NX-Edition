#!/usr/bin/env python3
"""V1-rc1: the whole WebGPU API and the whole C math library, for native mods.

The pinned lists name what known mods asked for, one name at a time, so a mod update calling one more
WebGPU or libm function (Dawnlight 4.1.0: wgpuRenderPassEncoderSetScissorRect, ...SetViewport, expm1f)
failed until a new NRO shipped. These two lists are the whole families instead:

  mod_abi_wgpu.txt  every wgpu* function Dawn's generated webgpu.h declares (the Dawn the NRO links);
  mod_abi_libm.txt  every global function devkitA64's libm.a defines (newlib's libm: same names and
                    meanings as glibc's for the C99/POSIX math functions).

ModAbiExports.cmake reads them like mod_abi_pinned.txt: each name is a link root and is exported.
Regenerate when Dawn or devkitA64 changes:

  gen-mod-abi-wholesale.py --webgpu-h <build>/_deps/dawn-build/gen/include/dawn/webgpu.h \\
      --nm <devkitA64>/bin/aarch64-none-elf-nm --libm <devkitA64>/aarch64-none-elf/lib/libm.a --out-dir platforms/switch
"""
import argparse
import re
import subprocess
from pathlib import Path

HEADER = "# Generated by platforms/switch/tools/gen-mod-abi-wholesale.py ({what}). Do not edit by hand.\n"


def wgpu_names(header: Path) -> list[str]:
    text = header.read_text(encoding="utf-8", errors="replace")
    # WGPU_EXPORT <type> wgpuName(...) WGPU_FUNCTION_ATTRIBUTE;
    names = set(re.findall(r"WGPU_EXPORT[^;(]*?\b(wgpu[A-Z]\w*)\s*\(", text))
    return sorted(names)


def libm_names(nm: str, libm: Path) -> list[str]:
    # Per member: what it defines and what it needs. A member that needs a name no libm or libc member defines
    # cannot be linked (newlib's cacoshl/casinl/catanhl need csqrtl/clogl/catanl, which it does not ship), so
    # its functions are left out -- and so is anything that needs them, until nothing changes.
    libc = libm.with_name("libc.a")
    defined_by: dict[str, set[str]] = {}
    needs: dict[str, set[str]] = {}
    everything: set[str] = set()
    for archive in (libm, libc):
        out = subprocess.run([nm, "-A", "-g", str(archive)], check=True, capture_output=True, text=True).stdout
        for line in out.splitlines():
            # "<archive>:<member>:<value> <type> <name>" (the archive path may hold a drive colon)
            m = re.match(r"^(.*?\.a):([^:]+):(.*)$", line.strip())
            if not m:
                continue
            head, parts = m.group(2), m.group(3).split()
            if not parts:
                continue
            if len(parts) == 2 and parts[0] == "U":
                if archive == libm:
                    needs.setdefault(head, set()).add(parts[1])
            elif len(parts) == 3:
                everything.add(parts[2])
                if archive == libm and parts[1] in ("T", "W"):
                    defined_by.setdefault(head, set()).add(parts[2])
    # Names starting with "__" are the compiler runtime (libgcc: soft long double, ...), always linked.
    broken = {m for m, n in needs.items() if {x for x in n - everything if not x.startswith("__")}}
    while True:
        gone = set().union(*(defined_by.get(m, set()) for m in broken)) if broken else set()
        more = {m for m, n in needs.items() if m not in broken and (n & gone)}
        if not more:
            break
        broken |= more
    names = set()
    for member, syms in defined_by.items():
        if member in broken:
            continue
        names |= {s for s in syms if re.fullmatch(r"[a-z][a-z0-9_]*", s)}
    return sorted(names)


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--webgpu-h", type=Path, required=True)
    ap.add_argument("--nm", required=True)
    ap.add_argument("--libm", type=Path, required=True)
    ap.add_argument("--out-dir", type=Path, required=True)
    a = ap.parse_args()
    wgpu = wgpu_names(a.webgpu_h)
    libm = libm_names(a.nm, a.libm)
    if len(wgpu) < 100 or len(libm) < 100:
        raise SystemExit(f"suspiciously few names: {len(wgpu)} wgpu, {len(libm)} libm")
    (a.out_dir / "mod_abi_wgpu.txt").write_text(
        HEADER.format(what="Dawn webgpu.h") + "".join(n + "\n" for n in wgpu), encoding="utf-8", newline="\n")
    (a.out_dir / "mod_abi_libm.txt").write_text(
        HEADER.format(what="devkitA64 libm.a") + "".join(n + "\n" for n in libm), encoding="utf-8", newline="\n")
    print(f"{len(wgpu)} wgpu, {len(libm)} libm")


if __name__ == "__main__":
    main()
