#!/usr/bin/env python3
"""DM1-b: the game's export surface, derived from the build instead of from a list of mods.

A native mod binds by name against the NRO's .dynsym. Until H38 that surface was the union of
what thirteen known mods asked for (mod_required_symbols.txt) plus a probe list; an update that
called one more game function failed until a new NRO shipped (Unrestricted Items 1.1.1 -> 1.1.2).

This tool names, instead, every global symbol the *game* defines: the objects compiled into the
dusklight target and dusk_internal, the JSystem libraries and Aurora's Dolphin API libraries
(GX, MTX, OS, PAD, VI...). Third-party archives -- abseil, Dawn, Rust std, SDL, curl, Mesa -- are
left out on purpose: ModAbiExports.cmake records that rooting all of them breaks the link
(abseil LowLevelAlloc, lstat64 from Rust std). The list goes to ld as --dynamic-list, which
exports each name and makes it a --gc-sections root.

  generate  --nm NM --out LIST [--report JSON] --objdir DIR... --archive A...
  classify  --nm NM --elf ELF --list LIST --names FILE   (host audit: exported/kept/absent)
"""
import argparse
import json
import pathlib
import re
import subprocess
import sys
import tempfile

# Defined, global. Weak/vague-linkage definitions (W, V) are inline functions and template
# instances: a mod compiles its own copy of those, and exporting thousands of them only grows
# .dynsym. Kept out; check_symbol_manifest reports any mod import that turns out to need one.
STRONG = set("TDBRGS")
# DM1-c: except the class data a mod cannot compile itself. A class whose virtual functions are all
# inline (J3DJointTree, J3DMaterialTable, mDoExt_MtxCalcAnmBlendTbl...) has its vtable, typeinfo and VTT
# emitted with vague linkage in every unit that uses it; a mod that constructs or derives from one
# imports _ZTV/_ZTI/_ZTS/_ZTT by name (Dawnlight 4.0.3, Hyrule Hide & Seek 0.4.1). Functions stay out.
VAGUE = set("VW")
CLASS_DATA = re.compile(r"^_ZT[VIST]")
NAME = re.compile(r"^[A-Za-z_][A-Za-z0-9_.$]*$")
# Names that must never be interposed through the export table.
EXCLUDE = re.compile(r"^(main|_start|__libnx_.*|__nx_.*|_init|_fini|__bss_.*|__end__|_end|end)$")


def nm_defined(nm: str, inputs: list[str]) -> dict[str, str]:
    """name -> type letter, for globally defined symbols of every input."""
    found: dict[str, str] = {}
    # One nm call over a response file: thousands of objects, no command-line limit.
    with tempfile.NamedTemporaryFile("w", suffix=".rsp", delete=False, encoding="utf-8") as rsp:
        for path in inputs:
            rsp.write('"' + path.replace("\\", "/") + '"\n')
        rsp_name = rsp.name
    try:
        out = subprocess.run([nm, "--defined-only", "--extern-only", "-P", "@" + rsp_name],
                             check=True, capture_output=True, text=True).stdout
    finally:
        pathlib.Path(rsp_name).unlink(missing_ok=True)
    for line in out.splitlines():
        parts = line.split()
        # -P: "name type value size"; archive headers look like "lib.a[obj.o]:"
        if len(parts) < 2 or parts[0].endswith(":"):
            continue
        name, kind = parts[0], parts[1]
        wanted = kind in STRONG or (kind in VAGUE and CLASS_DATA.match(name))
        if wanted and NAME.match(name) and not EXCLUDE.match(name):
            found.setdefault(name, kind)
    return found


def objects(dirs: list[str]) -> list[str]:
    files = []
    for d in dirs:
        root = pathlib.Path(d)
        files += sorted(str(p) for p in root.rglob("*") if p.suffix in (".obj", ".o") and p.is_file())
    return files


def generate(args) -> None:
    inputs = objects(args.objdir) + [a for a in args.archive if pathlib.Path(a).is_file()]
    found = nm_defined(args.nm, inputs)
    text = ["/* Generated by platforms/switch/tools/game_surface.py at link time. Do not edit. */", "{"]
    text += [f"  {name};" for name in sorted(found)]
    text.append("};")
    out = pathlib.Path(args.out)
    new = "\n".join(text) + "\n"
    if not out.exists() or out.read_text(encoding="utf-8") != new:
        out.write_text(new, encoding="utf-8")
    if args.report:
        kinds: dict[str, int] = {}
        for k in found.values():
            kinds[k] = kinds.get(k, 0) + 1
        pathlib.Path(args.report).write_text(json.dumps({
            "inputs": len(inputs), "symbols": len(found), "by_type": kinds}, indent=1), encoding="utf-8")
    print(f"game_surface: {len(found)} game symbols from {len(inputs)} inputs -> {out.name}")


def elf_names(nm: str, elf: str, dynamic: bool) -> set[str]:
    cmd = [nm, "--defined-only", "-P"] + (["-D"] if dynamic else []) + [elf]
    out = subprocess.run(cmd, check=True, capture_output=True, text=True).stdout
    return {line.split()[0] for line in out.splitlines() if line.split()}


def classify(args) -> None:
    """For each requested name: exported (in .dynsym), linked-not-exported, absent."""
    dyn = elf_names(args.nm, args.elf, True)
    full = elf_names(args.nm, args.elf, False)
    listed = set()
    for line in pathlib.Path(args.list).read_text(encoding="utf-8").splitlines():
        line = line.strip().rstrip(";")
        if NAME.match(line):
            listed.add(line)
    names = [n.strip() for n in pathlib.Path(args.names).read_text(encoding="utf-8").splitlines() if n.strip()]
    result = {"exported": [], "linked_not_exported": [], "absent_in_game_surface": [], "absent_not_game": []}
    for n in sorted(set(names)):
        if n in dyn:
            result["exported"].append(n)
        elif n in full:
            result["linked_not_exported"].append(n)
        elif n in listed:
            result["absent_in_game_surface"].append(n)  # listed but the link still lost it
        else:
            result["absent_not_game"].append(n)
    json.dump({k: {"count": len(v), "names": v} for k, v in result.items()}, sys.stdout, indent=1)


def main() -> None:
    p = argparse.ArgumentParser()
    sub = p.add_subparsers(dest="cmd", required=True)
    g = sub.add_parser("generate")
    g.add_argument("--nm", required=True)
    g.add_argument("--out", required=True)
    g.add_argument("--report")
    g.add_argument("--objdir", action="append", default=[])
    g.add_argument("--archive", action="append", default=[])
    c = sub.add_parser("classify")
    c.add_argument("--nm", required=True)
    c.add_argument("--elf", required=True)
    c.add_argument("--list", required=True)
    c.add_argument("--names", required=True)
    args = p.parse_args()
    generate(args) if args.cmd == "generate" else classify(args)


if __name__ == "__main__":
    main()
