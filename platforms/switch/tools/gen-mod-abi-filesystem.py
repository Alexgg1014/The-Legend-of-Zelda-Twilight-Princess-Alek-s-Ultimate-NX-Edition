#!/usr/bin/env python3
"""1.0.1: the whole std::filesystem of devkitA64's libstdc++ (the C++11 ABI members), for native mods.

The export surface (mod_abi_surface.txt) names what catalog mods import; a mod from elsewhere asked for two
std::filesystem functions nobody in the catalog used (Twilight HD HUD, GitHub issue #4: equivalent, read_symlink),
and one of them was not even linked. Like mod_abi_wgpu.txt / mod_abi_libm.txt, this writes the whole family, which
ModAbiExports.cmake pins (--undefined: linked) and exports (--dynamic-list):

  mod_abi_libstdcxx_fs.txt  every global function fs_ops.o, fs_dir.o and fs_path.o define (the C++11-ABI std::filesystem;
                            the cow-* members are the old ABI, which no Linux-built mod uses)

What Horizon cannot do comes back as an error_code (read_symlink, symlinks, hard links: no such support), as libstdc++
already does on bare metal. equivalent is the exception: Horizon has no inode numbers, so the loader binds a mod's
import of it to a shim that compares paths (src/dusk/mods/loader/elf_runtime_policy.cpp).

  gen-mod-abi-filesystem.py --nm <devkitA64>/bin/aarch64-none-elf-nm \
      --libstdcxx <devkitA64>/aarch64-none-elf/lib/libstdc++.a --out platforms/switch/mod_abi_libstdcxx_fs.txt
"""
import argparse
import subprocess
from pathlib import Path

MEMBERS = ("fs_ops.o", "fs_dir.o", "fs_path.o")
HEADER = ("# Generated by platforms/switch/tools/gen-mod-abi-filesystem.py (devkitA64 libstdc++.a: "
          + ", ".join(MEMBERS) + "). Do not edit by hand.\n")


def names(nm: str, archive: Path) -> list[str]:
    out = subprocess.run([nm, "-A", "--defined-only", str(archive)], check=True, capture_output=True,
                         text=True).stdout
    found = set()
    for line in out.splitlines():
        # "<archive>:<member>:<value> <type> <name>" (the archive path may hold a drive colon)
        parts = line.split()
        if len(parts) < 3:
            continue
        location, kind, name = parts[0], parts[-2], parts[-1]
        member = location.rstrip(":").rsplit(":", 2)[-2] if location.count(":") >= 2 else ""
        if member in MEMBERS and kind in ("T", "W"):
            found.add(name)
    return sorted(found)


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--nm", required=True)
    ap.add_argument("--libstdcxx", type=Path, required=True)
    ap.add_argument("--out", type=Path, required=True)
    a = ap.parse_args()
    found = names(a.nm, a.libstdcxx)
    if len(found) < 100:
        raise SystemExit(f"suspiciously few std::filesystem names: {len(found)}")
    for must in ("_ZNSt10filesystem12read_symlinkERKNS_7__cxx114pathERSt10error_code",
                 "_ZNSt10filesystem10equivalentERKNS_7__cxx114pathES3_RSt10error_code"):
        if must not in found:
            raise SystemExit(f"{must} is not in {', '.join(MEMBERS)}")
    a.out.write_text(HEADER + "".join(n + "\n" for n in found), encoding="utf-8", newline="\n")
    print(f"{len(found)} names -> {a.out}")


if __name__ == "__main__":
    main()
