/* From code_arena_test.c. */
const code_arena_ops *code_arena_test_ops(void);
void code_arena_test_reset_kernel(uint32_t limit);
uint32_t code_arena_test_live_objects(void);
uint32_t code_arena_test_peak_objects(void);
void code_arena_test_fail(const char *what);
#define CHECK(cond)                                                                                \
    do {                                                                                           \
        if (!(cond)) {                                                                             \
            code_arena_test_fail(#cond);                                                           \
        }                                                                                          \
    } while (0)

/* From the generated targets.c. */
extern int (*const k_targets[])(int);
extern int (*const k_hooks[])(int);
extern int (*g_orig[])(int);
extern const int k_target_count;

/* ------------------------------------------- what funchook_os_switch.c is on the console -- */

const size_t page_size = 0x1000;
/* funchook's handle is plain memory; its size comes from funchook.c. */
extern const size_t funchook_size;

void *funchook_alloc(void)
{
    void *p = calloc(1, (funchook_size + page_size - 1) & ~(page_size - 1));
    return p;
}

int funchook_free(void *funchook)
{
    free(funchook);
    return 0;
}

const char *funchook_strerror(int errnum, char *buf, size_t buflen)
{
    snprintf(buf, buflen, "error %d", errnum);
    return buf;
}

int funchook_unprotect_begin(void *funchook, void *mstate, void *start, size_t len)
{
    (void)funchook;
    (void)mstate;
    (void)start;
    (void)len;
    return -1; /* as on the console: patch sites go through commit_code_patch */
}

int funchook_unprotect_end(void *funchook, const void *mstate)
{
    (void)funchook;
    (void)mstate;
    return -1;
}

void *funchook_resolve_func(void *funchook, void *func)
{
    (void)funchook;
    return func;
}

int commit_code_patch(void *target, const void *expected, const void *replacement, size_t size)
{
    uint8_t *page = (uint8_t *)((uintptr_t)target & ~(uintptr_t)0xFFF);
    const size_t span = (((uintptr_t)target + size + 0xFFF) & ~(uintptr_t)0xFFF) - (uintptr_t)page;
    if (memcmp(target, expected, size) != 0) {
        return -4;
    }
    if (mprotect(page, span, PROT_READ | PROT_WRITE | PROT_EXEC) != 0) {
        return -5;
    }
    memcpy(target, replacement, size);
    __builtin___clear_cache((char *)target, (char *)target + size);
    mprotect(page, span, PROT_READ | PROT_EXEC);
    return 0;
}

static pthread_mutex_t s_lock = PTHREAD_MUTEX_INITIALIZER;
static code_arenas s_arenas;
static int s_initialized;

code_arenas *funchook_arenas_acquire(void)
{
    pthread_mutex_lock(&s_lock);
    if (!s_initialized) {
        s_initialized = 1;
        code_arenas_init(&s_arenas, code_arena_test_ops());
    }
    return &s_arenas;
}

void funchook_arenas_release(void)
{
    pthread_mutex_unlock(&s_lock);
}

int funchook_arenas_permitted(void *funchook)
{
    (void)funchook;
    return 1;
}

/* ---------------------------------------------------------------------- the test -- */

static funchook_t *g_handle[256];

static int hook_range(int first, int count)
{
    for (int i = first; i < first + count; i++) {
        funchook_t *fh = funchook_create();
        void *fn = (void *)k_targets[i];
        int rv = funchook_prepare(fh, &fn, (void *)k_hooks[i]);
        if (rv == 0) {
            g_orig[i] = (int (*)(int))fn;
            rv = funchook_install(fh, 0);
        }
        if (rv != 0) {
            fprintf(stderr, "hook %d: %s\n", i, funchook_error_message(fh));
            funchook_destroy(fh);
            return rv;
        }
        g_handle[i] = fh;
    }
    return 0;
}

static void unhook_range(int first, int count)
{
    for (int i = first; i < first + count; i++) {
        CHECK(funchook_uninstall(g_handle[i], 0) == 0);
        CHECK(funchook_destroy(g_handle[i]) == 0);
        g_handle[i] = NULL;
    }
}

static int all_hooked(int first, int count, int hooked)
{
    for (int i = first; i < first + count; i++) {
        const int want = 3 * 7 + i + (hooked ? 1000 : 0);
        if (k_targets[i](7) != want) {
            fprintf(stderr, "target %d returned %d, want %d\n", i, k_targets[i](7), want);
            return 0;
        }
    }
    return 1;
}

void run_funchook_part(void)
{
    code_arena_test_reset_kernel(10);
    CHECK(k_target_count >= 124);
    const int cosmetics = 0, roll = 28, rando = 32;
    CHECK(hook_range(cosmetics, 28) == 0);
    CHECK(all_hooked(cosmetics, 28, 1));
    CHECK(code_arena_test_live_objects() == 1);
    CHECK(hook_range(roll, 4) == 0);
    CHECK(all_hooked(0, 32, 1));
    CHECK(code_arena_test_live_objects() == 1);
    CHECK(hook_range(rando, 92) == 0);
    CHECK(all_hooked(0, 124, 1));
    CHECK(code_arena_test_live_objects() == 2);

    for (int cycle = 0; cycle < 5; cycle++) {
        unhook_range(cosmetics, 28);
        CHECK(all_hooked(cosmetics, 28, 0));  /* the originals again */
        CHECK(all_hooked(roll, 96, 1));       /* the others never stopped */
        CHECK(hook_range(cosmetics, 28) == 0);
        CHECK(all_hooked(0, 124, 1));
    }
    CHECK(code_arena_test_live_objects() == 2 && code_arena_test_peak_objects() == 2);
    char line[320];
    funchook_arenas_acquire();
    code_arena_describe(&s_arenas, line, sizeof line);
    funchook_arenas_release();
    printf("funchook     124 real hooks (28 + 4 + 92) installed, called and removed through the arenas; "
           "Cosmetics off/on x5; %u CodeMemory object(s), peak %u, kernel limit 10\n",
        code_arena_test_live_objects(), code_arena_test_peak_objects());
    printf("             %s\n", line);
    unhook_range(0, 124);
    CHECK(all_hooked(0, 124, 0));
}
