/* H37: part B of code_arena_test.c -- funchook itself hooking real functions through the code
 * arenas, on aarch64 (under qemu-user), against the same fake kernel.
 *
 * funchook.c is v1.1.3 as the build fetches it, patched by cmake/PatchFunchook.cmake and compiled
 * with __SWITCH__ so its page writes take the patched route; funchook_arena_glue.c and
 * code_arena.c are the files the console build compiles. Only what needs libnx is replaced, here:
 * funchook's allocation of its own handle, the lock around the arena manager, and the write of
 * the two instructions over a hooked function (code_patch_switch.c on the console; mprotect here).
 *
 * The functions hooked are generated by test-code-arena.sh: target_i(x) returns 3x + i, and its
 * hook returns the original -- called through the trampoline funchook handed back -- plus 1000.
 */
#define _GNU_SOURCE
#include "code_arena.h"
#include "funchook.h"

#include <pthread.h>
#include <stdint.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <sys/mman.h>
