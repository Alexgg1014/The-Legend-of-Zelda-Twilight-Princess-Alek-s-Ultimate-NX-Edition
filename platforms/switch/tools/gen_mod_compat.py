#!/usr/bin/env python3
"""aleks2 (DM2-c): the code platforms/switch/mod_compat_symbols.txt describes.

  gen_mod_compat.py generate [--check]
      Rewrite include/aleks2/mod_compat_templates.inc and src/dusk/mods/compat/mod_compat.cpp from the
      list. --check writes nothing and fails if either is stale or a header lacks the compat include
      (CMake runs this at configure time).
  gen_mod_compat.py update --audit catalog-audit-raw.json [--dry-run]
      Read a catalog audit (platforms/switch/tools/package_audit.py), add to the list every missing
      by-name hook that is a template instance (`name<args>`), matches a pc-prefix, or (DM3) is a member
      function declared `inline` in a header and defined in one source file (`Class::method`), add the
      compat include to any header that needs it, then generate. What it cannot work out is printed for
      a person to add by hand, and the exit status is 1.

  DM3, out-of-line members: `generate` also makes the two source edits each `out-of-line` entry asks
  for (idempotent; --check only verifies them): the header's `inline` becomes ALEKS2_OUT_OF_LINE_DECL
  and the definition gains ALEKS2_OUT_OF_LINE (include/global.h: `inline` and nothing off Switch, so
  the PC build is unchanged; nothing and noinline on Switch).

The list file says what each category is. Every path is relative to the source root (--root, default:
two levels above this file's folder).
"""
import argparse
import json
import re
import sys
from pathlib import Path

LIST = Path("platforms/switch/mod_compat_symbols.txt")
INC = Path("include/aleks2/mod_compat_templates.inc")
CPP = Path("src/dusk/mods/compat/mod_compat.cpp")
GENERATED = "// Generated by platforms/switch/tools/gen_mod_compat.py from platforms/switch/mod_compat_symbols.txt.\n" \
            "// Do not edit by hand.\n"
# The game's typedefs, for matching a hook name ("cLib_calcTimer<short int>") to source ("s16").
DWARF_TYPES = {
    "signed char": "s8", "unsigned char": "u8", "short int": "s16", "short unsigned int": "u16",
    "int": "int", "unsigned int": "u32", "long int": "s64", "long unsigned int": "u64",
    "float": "f32", "double": "f64", "bool": "bool", "char": "char",
}
RETURNS = {"void": "", "zero": "    return 0;\n"}


def macro_for(header):
    return "ALEKS2_MOD_COMPAT_" + re.sub(r"[^A-Za-z0-9]", "_", Path(header).name).upper()


def include_block(header):
    macro = macro_for(header)
    return ("#if defined(__SWITCH__)\n"
            "// aleks2 (DM2-c): template instances catalog mods hook by name, out of line\n"
            "// (platforms/switch/mod_compat_symbols.txt).\n"
            f"#define {macro}\n"
            "#include \"aleks2/mod_compat_templates.inc\"\n"
            f"#undef {macro}\n"
            "#endif\n")


class CompatList:
    def __init__(self, path):
        self.path = path
        self.lines = path.read_text(encoding="utf-8").splitlines()
        self.templates = []   # (header, origin, hook, decl)
        self.pc_only = []     # (category, kind, symbol, ret)
        self.prefixes = []    # (category, prefix)
        self.out_of_line = []  # (header, source, origin, Class::method)
        for number, line in enumerate(self.lines, 1):
            if not line.strip() or line.startswith("#"):
                continue
            kind = line.split()[0]
            if kind == "template":
                head, sep, decl = line.partition("|")
                parts = head.split(None, 3)
                if not sep or len(parts) != 4 or not decl.strip():
                    sys.exit(f"{path}:{number}: template <header> <origin> <hook> | <declarator>")
                self.templates.append((parts[1], parts[2], parts[3].strip(), decl.strip()))
            elif kind == "pc-only":
                parts = line.split()
                if len(parts) != 5 or parts[2] not in ("hook", "import") or parts[4] not in RETURNS:
                    sys.exit(f"{path}:{number}: pc-only <category> <hook|import> <symbol> <void|zero>")
                self.pc_only.append(tuple(parts[1:]))
            elif kind == "out-of-line":
                parts = line.split()
                if len(parts) != 5 or "::" not in parts[4]:
                    sys.exit(f"{path}:{number}: out-of-line <header under include/> <source> <origin> <Class::method>")
                self.out_of_line.append(tuple(parts[1:]))
            elif kind == "pc-prefix":
                parts = line.split()
                if len(parts) != 3:
                    sys.exit(f"{path}:{number}: pc-prefix <category> <prefix>")
                self.prefixes.append((parts[1], parts[2]))
            else:
                sys.exit(f"{path}:{number}: unknown entry {kind!r}")

    def known(self):
        return ({t[2] for t in self.templates} | {t[3] for t in self.templates} | {p[2] for p in self.pc_only}
                | {o[3] for o in self.out_of_line})


def render(compat):
    inc = [GENERATED, "// Included at the end of each header below, with that header's macro defined; no include guard.\n"]
    by_header = {}
    for header, origin, hook, decl in compat.templates:
        by_header.setdefault(header, []).append((origin, hook, decl))
    for header, entries in by_header.items():
        inc.append(f"\n#ifdef {macro_for(header)}  // {header}\n")
        for origin, hook, decl in entries:
            inc.append(f"extern template {decl};  // {origin}: {hook}\n")
        inc.append("#endif\n")

    cpp = [GENERATED,
           "// The out-of-line copies the extern template declarations in include/aleks2/mod_compat_templates.inc\n"
           "// promise, and the neutral stubs for PC-only symbols (docs/investigaciones/dm2c-capas-generales.md).\n"
           "#if defined(__SWITCH__)\n"]
    for header in by_header:
        cpp.append(f"#include \"{header}\"\n")
    cpp.append("\n// 1. template instances\n")
    for header, entries in by_header.items():
        for origin, hook, decl in entries:
            cpp.append(f"template {decl};  // {origin}: {hook}\n")
    cpp.append("\n// 2. PC-only symbols: the exact name, no work. Weak, so that a real definition linked in wins\n"
               "// (borealis' own discord stub.cpp, should the Switch build ever compile a caller). The nops make\n"
               "// the body long enough for any hook patch (12 bytes); the return value is in x0. Nothing in the\n"
               "// game calls them: platforms/switch/CMakeLists.txt keeps them with -Wl,--undefined.\n")
    for index, (category, kind, symbol, ret) in enumerate(compat.pc_only):
        fn = f"aleks2_pc_only_{index}"
        signature = "long" if ret == "zero" else "void"
        cpp.append(f"// {category} ({kind})\n"
                   f"extern \"C\" __attribute__((used, noinline, weak, visibility(\"default\"))) {signature} {fn}()"
                   f" __asm__(\"{symbol}\");\n"
                   f"extern \"C\" {signature} {fn}() {{\n"
                   f"    __asm__ volatile(\"nop\\n\\tnop\\n\\tnop\");\n"
                   f"{RETURNS[ret]}}}\n")
    cpp.append("#endif\n")
    return "".join(inc), "".join(cpp)


DECL_MACRO = "ALEKS2_OUT_OF_LINE_DECL"
DEF_MACRO = "ALEKS2_OUT_OF_LINE"


def _decl_pattern(method, keyword):
    return re.compile(r"^([ \t]*)" + re.escape(keyword) + r"([ \t]+[^;(\n]*?\b)" + re.escape(method) + r"[ \t]*\(", re.M)


def _def_pattern(cls, method, prefix=""):
    return re.compile(r"^" + re.escape(prefix) + r"((?!" + re.escape(DEF_MACRO) + r"\b)[A-Za-z_][^;\n(]*?\b)" +
                      re.escape(cls) + r"::" + re.escape(method) + r"[ \t]*\([^;{]*\)[^;{]*\{", re.M)


def out_of_line_problems(root, compat, fix=False):
    """The source edits each out-of-line entry needs: [] when all are in place. With fix, make them."""
    problems = []
    for header, source, origin, name in compat.out_of_line:
        cls, method = name.rsplit("::", 1)
        cls = cls.split("::")[-1]
        for rel, kind in ((Path("include") / header, "header"), (Path(source), "source")):
            path = root / rel
            if not path.exists():
                problems.append(f"{name}: no such {kind} {rel.as_posix()}")
                continue
            data = path.read_bytes().decode("utf-8")
            crlf = "\r\n" in data
            text = data.replace("\r\n", "\n")
            if kind == "header":
                done = len(_decl_pattern(method, DECL_MACRO).findall(text))
                todo = _decl_pattern(method, "inline").findall(text)
                if done == 1 and not todo:
                    continue
                if done == 0 and len(todo) == 1 and f"class {cls}" in text:
                    if fix:
                        text = _decl_pattern(method, "inline").sub(lambda m: m.group(1) + DECL_MACRO + m.group(2) + method + "(", text, 1)
                    else:
                        problems.append(f"{name}: {rel.as_posix()} still declares it inline (generate fixes it)")
                        continue
                else:
                    problems.append(f"{name}: {rel.as_posix()} has {len(todo)} inline and {done} {DECL_MACRO} "
                                    f"declarations of {method}; fix by hand")
                    continue
            else:
                done = len(_def_pattern(cls, method, DEF_MACRO + " ").findall(text))
                todo = _def_pattern(cls, method).findall(text)
                if done == 1 and not todo:
                    continue
                if done == 0 and len(todo) == 1:
                    if fix:
                        text = _def_pattern(cls, method).sub(lambda m: DEF_MACRO + " " + m.group(0), text, 1)
                    else:
                        problems.append(f"{name}: {rel.as_posix()} defines it without {DEF_MACRO} (generate fixes it)")
                        continue
                else:
                    problems.append(f"{name}: {rel.as_posix()} has {len(todo)} plain and {done} marked definitions; "
                                    "fix by hand")
                    continue
            path.write_bytes((text.replace("\n", "\r\n") if crlf else text).encode("utf-8"))
            print(f"out-of-line {name}: edited {rel.as_posix()}")
    return problems


def find_inline_member(root, name):
    """(header under include/, source) for `Class::method` declared inline in one header and defined in one source."""
    m = re.fullmatch(r"(\w+)::(\w+)", name)
    if not m:
        return None
    cls, method = m.groups()
    headers = []
    for path in (root / "include").rglob("*.h"):
        text = path.read_text(encoding="utf-8", errors="replace")
        if f"class {cls}" in text and len(_decl_pattern(method, "inline").findall(text)) == 1:
            headers.append(path.relative_to(root / "include").as_posix())
    sources = []
    for path in (root / "src").rglob("*.cpp"):
        text = path.read_text(encoding="utf-8", errors="replace")
        if f"{cls}::{method}" in text and _def_pattern(cls, method).search(text.replace("\r\n", "\n")):
            sources.append(path.relative_to(root).as_posix())
    if len(headers) == 1 and len(sources) == 1:
        return headers[0], sources[0]
    return None


def header_problems(root, compat):
    problems = []
    for header in sorted({t[0] for t in compat.templates}):
        path = root / "include" / header
        if not path.exists():
            problems.append(f"{header}: no such header under include/")
        elif macro_for(header) not in path.read_text(encoding="utf-8", errors="replace"):
            problems.append(f"{header}: lacks the compat include (gen_mod_compat.py generate adds it)")
    return problems


def add_include(root, header):
    path = root / "include" / header
    data = path.read_bytes().decode("utf-8")
    if macro_for(header) in data:
        return
    crlf = "\r\n" in data
    text = data.replace("\r\n", "\n")
    block = include_block(header)
    # Before the include guard's closing #endif when there is one, else at the end.
    match = re.search(r"\n#endif[^\n]*\n*\Z", text)
    if match:
        head = text[:match.start() + 1]
        text = head + ("" if head.endswith("\n\n") else "\n") + block + "\n" + text[match.start() + 1:]
    else:
        text += "\n" + block
    path.write_bytes((text.replace("\n", "\r\n") if crlf else text).encode("utf-8"))
    print(f"added the compat include to include/{header}")


def find_template(root, name):
    """(header, template text) for a non-inline function template `name` under include/."""
    short = name.split("::")[-1]
    pattern = re.compile(r"template\s*<\s*(?:typename|class)\s+(\w+)\s*>\s*\n"
                         r"(?!\s*inline)\s*([\w:<>\*& ]+?)\s+((?:\w+::)*" + re.escape(short) + r")\s*\(([^)]*)\)\s*\{")
    hits = []
    for path in (root / "include").rglob("*.h"):
        text = path.read_text(encoding="utf-8", errors="replace")
        for m in pattern.finditer(text):
            if m.group(3) == name or m.group(3).endswith("::" + name) or name.endswith(m.group(3)):
                hits.append((path.relative_to(root / "include").as_posix(), m))
    return hits


def declarator(match, args):
    param, ret, qual, params = match.groups()
    sub = lambda s: re.sub(rf"\b{param}\b", args, s)
    types = []
    for p in (x.strip() for x in params.split(",") if x.strip()):
        p = re.sub(r"\s*\w+$", "", p) if re.search(r"[\w\*&]\s+\w+$", p) else p  # drop the parameter name
        types.append(sub(p))
    return f"{sub(ret.strip())} {qual}<{args}>({', '.join(types)})"


def update(root, compat, audit_path, dry_run):
    audit = json.loads(Path(audit_path).read_text(encoding="utf-8"))
    missing = {}
    for mod in audit.get("mods", []):
        check = mod.get("elf_check") or {}
        for name in (check.get("hooks") or {}).get("missing", []):
            missing.setdefault(("hook", str(name)), set()).add(mod.get("id"))
        for name in (check.get("imports") or {}).get("missing", []):
            name = str(name).split(" (")[0]
            missing.setdefault(("import", name), set()).add(mod.get("id"))
    known = compat.known()
    added, manual = [], []
    for (kind, name), mods in sorted(missing.items()):
        if name in known:
            continue
        who = ", ".join(sorted(m for m in mods if m))
        category = next((c for c, p in compat.prefixes if name.startswith(p)), None)
        if category and not name.startswith("_Z"):
            manual.append(f"{name} ({who}): PC-only ({category}) but demangled; the stub needs the mangled name")
            continue
        if category:
            added.append(f"# {who}\npc-only {category} {kind} {name} {'void' if kind == 'hook' else 'zero'}")
            continue
        m = re.fullmatch(r"((?:\w+::)*\w+)<([^<>]+)>", name)
        if kind == "hook" and not m:
            member = find_inline_member(root, name)
            if member:
                added.append(f"# {who}\nout-of-line {member[0]} {member[1]} catalog {name}")
            elif re.fullmatch(r"\w+::\w+", name):
                manual.append(f"{name} ({who}): not one inline declaration + one definition; see the out-of-line category")
            continue
        if kind != "hook" or not m:
            continue  # not this layer's (libc, services, ...): the audit reports it as it is
        base, args = m.groups()
        hits = find_template(root, base)
        if len(hits) != 1:
            manual.append(f"{name} ({who}): {len(hits)} non-inline templates match; add a template line by hand")
            continue
        header, match = hits[0]
        decl = declarator(match, DWARF_TYPES.get(args.strip(), args.strip()))
        added.append(f"# {who}\ntemplate {header} catalog {name} | {decl}")
    for entry in added:
        print("add:", entry.replace("\n", " "))
    for entry in manual:
        print("manual:", entry)
    if added and not dry_run:
        text = compat.path.read_text(encoding="utf-8").rstrip("\n") + "\n\n# --- added by gen_mod_compat.py update ---\n"
        compat.path.write_text(text + "\n".join(added) + "\n", encoding="utf-8")
        compat = CompatList(compat.path)
    if not dry_run:
        for header in sorted({t[0] for t in compat.templates}):
            add_include(root, header)
        write(root, compat)
        manual += out_of_line_problems(root, compat, fix=True)
    return 1 if manual else 0


def write(root, compat):
    inc, cpp = render(compat)
    for rel, text in ((INC, inc), (CPP, cpp)):
        path = root / rel
        path.parent.mkdir(parents=True, exist_ok=True)
        if not path.exists() or path.read_text(encoding="utf-8") != text:
            path.write_text(text, encoding="utf-8", newline="\n")
            print(f"wrote {rel.as_posix()}")


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--root", type=Path, default=Path(__file__).resolve().parents[3])
    sub = parser.add_subparsers(dest="command", required=True)
    gen = sub.add_parser("generate")
    gen.add_argument("--check", action="store_true")
    upd = sub.add_parser("update")
    upd.add_argument("--audit", required=True)
    upd.add_argument("--dry-run", action="store_true")
    args = parser.parse_args()
    root = args.root
    compat = CompatList(root / LIST)
    if args.command == "update":
        return update(root, compat, args.audit, args.dry_run)
    if args.check:
        inc, cpp = render(compat)
        problems = header_problems(root, compat) + out_of_line_problems(root, compat)
        for rel, text in ((INC, inc), (CPP, cpp)):
            path = root / rel
            if not path.exists() or path.read_text(encoding="utf-8") != text:
                problems.append(f"{rel.as_posix()} is stale: run gen_mod_compat.py generate")
        for problem in problems:
            print("gen_mod_compat:", problem, file=sys.stderr)
        return 1 if problems else 0
    for header in sorted({t[0] for t in compat.templates if (root / "include" / t[0]).exists()}):
        add_include(root, header)
    write(root, compat)
    problems = header_problems(root, compat) + out_of_line_problems(root, compat, fix=True)
    for problem in problems:
        print("gen_mod_compat:", problem, file=sys.stderr)
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main())
